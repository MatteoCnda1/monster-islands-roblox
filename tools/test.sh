#!/usr/bin/env bash
# Runs the unit tests against the real code of src/ (outside Roblox).
#
# The luau CLI has no file I/O, so this script first bundles the source text of every
# src/**/*.luau file into build/test_sources.luau ({ ["shared/Utility/Logger"] = "<source>", ... }).
# tests/run_tests.luau then compiles every file (syntax check) and executes the src/shared modules
# with loadstring and a fake `script` (see its header).
set -euo pipefail

cd "$(dirname "$0")/.."

LUAU_BIN="luau"
if ! command -v luau >/dev/null 2>&1; then
    LUAU_BIN="$HOME/.cargo/bin/luau"
fi

BUNDLE="build/test_sources.luau"
DELIM="==========" # long-string level used to embed sources: [==========[ ... ]==========]

if grep -rlF "]${DELIM}]" src >/dev/null 2>&1; then
    echo "error: a file in src contains ']${DELIM}]', change DELIM in tools/test.sh" >&2
    exit 1
fi

mkdir -p build
{
    echo "-- AUTO-GENERATED by tools/test.sh from src/. Do not edit."
    echo "return {"
    while IFS= read -r file; do
        rel="${file#src/}"
        rel="${rel%.luau}"
        printf '\t["%s"] = [%s[\n' "$rel" "$DELIM"
        cat "$file"
        printf '\n]%s],\n' "$DELIM"
    done < <(find src -type f -name '*.luau' | LC_ALL=C sort)
    echo "}"
} > "$BUNDLE"

echo "Running Monster Islands Test Suite..."
"$LUAU_BIN" tests/run_tests.luau
